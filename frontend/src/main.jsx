import React from 'react';
import { MotionConfig } from 'framer-motion';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { AuthProvider } from './context/AuthContext';
import { ToastProvider } from './context/ToastContext';
import App from './App';
import ScrollManager from './components/ScrollManager';
import './styles.css';
const client = new QueryClient({ defaultOptions: { queries: { staleTime: 45_000, retry: 1, refetchOnWindowFocus: false } } });
createRoot(document.getElementById('root')).render(<React.StrictMode><QueryClientProvider client={client}><BrowserRouter><ScrollManager/><AuthProvider><ToastProvider><MotionConfig reducedMotion="user"><App/></MotionConfig></ToastProvider></AuthProvider></BrowserRouter></QueryClientProvider></React.StrictMode>);
