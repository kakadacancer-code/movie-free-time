<?php

use Illuminate\Support\Facades\Route;
use App\Http\Controllers\AuthController;
use App\Http\Controllers\CatalogController;
use App\Http\Controllers\CommunityController;
use App\Http\Controllers\AdminController;
use App\Http\Controllers\AdminContentController;
use App\Http\Controllers\ImportController;
use App\Http\Controllers\EpisodeController;

Route::prefix('v1')->group(function () {
    Route::get('/home', [CatalogController::class, 'home']);
    Route::get('/titles', [CatalogController::class, 'index']);
    Route::get('/movies', [CatalogController::class, 'movies']);
    Route::get('/donghua', [CatalogController::class, 'donghua']);
    Route::get('/anime', [CatalogController::class, 'anime']);
    Route::get('/titles/{slug}', [CatalogController::class, 'show']);
    Route::get('/titles/{slug}/video', [\App\Http\Controllers\VideoController::class, 'show']);
    Route::get('/titles/{slug}/episodes/{number}/video', [EpisodeController::class, 'video'])->whereNumber('number');
    Route::get('/genres', [CatalogController::class, 'genres']);
    Route::get('/categories', [CatalogController::class, 'categories']);
    Route::get('/articles', [CatalogController::class, 'articles']);
    Route::get('/articles/{slug}', [CatalogController::class, 'article']);
    Route::get('/search', [CatalogController::class, 'search']);
    Route::get('/settings', [CatalogController::class, 'settings']);
    Route::get('/titles/{id}/reviews', [CommunityController::class, 'reviews']);
    Route::post('/auth/register', [AuthController::class, 'register'])->middleware('throttle:8,1');
    Route::post('/auth/login', [AuthController::class, 'login'])->middleware('throttle:8,1');
    Route::middleware(['auth:sanctum', 'active'])->group(function () {
        Route::post('/auth/logout', [AuthController::class, 'logout']);
        Route::get('/me', [AuthController::class, 'me']);
        Route::patch('/me', [AuthController::class, 'update']);
        Route::get('/me/watchlist', [CommunityController::class, 'watchlist']);
        Route::post('/me/watchlist', [CommunityController::class, 'saveWatchlist']);
        Route::delete('/me/watchlist/{id}', [CommunityController::class, 'removeWatchlist']);
        Route::post('/titles/{id}/ratings', [CommunityController::class, 'rate']);
        Route::post('/titles/{id}/reviews', [CommunityController::class, 'review']);
        Route::post('/articles/{id}/comments', [CommunityController::class, 'comment']);
        Route::post('/reports', [CommunityController::class, 'report']);
        Route::prefix('admin')->middleware('role:admin,editor')->group(function () {
            Route::get('/dashboard', [AdminController::class, 'dashboard']);
            Route::get('/analytics', [AdminController::class, 'analytics']);
            Route::get('/titles', [AdminContentController::class, 'titles']);
            Route::post('/titles', [AdminContentController::class, 'storeTitle']);
            Route::put('/titles/{id}', [AdminContentController::class, 'updateTitle']);
            Route::delete('/titles/{id}', [AdminContentController::class, 'deleteTitle']);
            Route::post('/titles/bulk', [AdminContentController::class, 'bulkTitles']);
            Route::get('/titles/{id}/episodes', [EpisodeController::class, 'index']);
            Route::post('/titles/{id}/episodes', [EpisodeController::class, 'store']);
            Route::put('/episodes/{id}', [EpisodeController::class, 'update']);
            Route::delete('/episodes/{id}', [EpisodeController::class, 'destroy']);
            Route::get('/articles', [AdminContentController::class, 'articles']);
            Route::post('/articles', [AdminContentController::class, 'storeArticle']);
            Route::put('/articles/{id}', [AdminContentController::class, 'updateArticle']);
            Route::delete('/articles/{id}', [AdminContentController::class, 'deleteArticle']);
            Route::post('/genres', [AdminContentController::class, 'storeGenre']);
            Route::put('/genres/{id}', [AdminContentController::class, 'updateGenre']);
            Route::delete('/genres/{id}', [AdminContentController::class, 'deleteGenre']);
            Route::post('/categories', [AdminContentController::class, 'storeCategory']);
            Route::delete('/categories/{id}', [AdminContentController::class, 'deleteCategory']);
            Route::get('/moderation', [AdminController::class, 'moderation']);
            Route::patch('/moderation/{type}/{id}', [AdminController::class, 'moderate']);
            Route::post('/videos', [\App\Http\Controllers\VideoController::class, 'upload']);
            Route::get('/media', [AdminController::class, 'media']);
            Route::post('/media', [AdminController::class, 'upload']);
            Route::delete('/media/{id}', [AdminController::class, 'deleteMedia']);
            Route::get('/imports/search', [ImportController::class, 'search']);
            Route::post('/imports/confirm', [ImportController::class, 'confirm']);
            Route::middleware('role:admin')->group(function () {
                Route::get('/users', [AdminController::class, 'users']);
                Route::patch('/users/{id}', [AdminController::class, 'updateUser']);
                Route::get('/reports', [AdminController::class, 'reports']);
                Route::patch('/reports/{id}', [AdminController::class, 'resolveReport']);
                Route::get('/settings', [AdminController::class, 'settings']);
                Route::put('/settings', [AdminController::class, 'updateSettings']);
                Route::get('/audit-logs', [AdminController::class, 'auditLogs']);
            });
        });
    });
});
